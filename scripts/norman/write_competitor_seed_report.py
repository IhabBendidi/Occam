#!/usr/bin/env python
"""Write the paper-grade competitor report for norman_combo: every metric, seed and split.

WHY THIS FILE EXISTS
    These numbers go into a paper, so they must be regenerable EXACTLY from the primary
    record, not transcribed. This reads `data/release/metrics/
    norman_competitors_by_seed_split.csv` (itself extracted straight from each split's
    cell-eval results.csv) and writes `docs/norman_competitors_seeds.md`. Re-run it when
    more seeds land; nothing in the document is typed by hand.

THE UNIT OF REPLICATION IS THE SEED
    Splits re-slice the same cells from the SAME trained checkpoint, so their spread is
    panel-sampling noise, not model variance. Every seed-level number here is the mean of
    that seed's 5 splits, and every `SD` / `SEM` is ACROSS SEEDS. Pooling all splits would
    inflate n by 5x -- see scripts/seed_split_test.py.

USAGE
    python scripts/norman/write_competitor_seed_report.py
"""

from __future__ import annotations

import csv
import math
import os
import statistics as st
from collections import defaultdict

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(REPO, "data/release/metrics/norman_competitors_by_seed_split.csv")
OUT = os.path.join(REPO, "docs/norman_competitors_seeds.md")
PANELS = ("additive", "nonadditive")
HEAD = ("pearson_delta", "mae", "overlap_at_N", "discrimination_score_l1")
LOWER = {"mae", "mse", "mae_delta", "mse_delta"}
CONTEXT = {"de_nsig_counts_pred", "de_nsig_counts_real", "n_perturbations"}
ARM_LABEL = {"txpert": "TxPert", "cellflow": "CellFlow", "state": "State",
             "perturbdiff": "PerturbDiff"}
MECH = {"txpert": "native additive sum of the two perturbation embeddings",
        "cellflow": "native set aggregation, max_combination_length=2",
        "state": "decode_seq_mean at the export boundary (our extension of its "
                 "consecutive forward passes)",
        "perturbdiff": "decode_seq_mean at the export boundary (ours; no published "
                       "combinatorial protocol)"}


def load():
    d = defaultdict(dict)          # (arm, panel, metric) -> {(seed, split): value}
    with open(SRC) as fh:
        for r in csv.DictReader(fh):
            d[(r["arm"], r["panel"], r["metric"])][(int(r["seed"]), int(r["split"]))] = \
                float(r["value"])
    return d


def seed_means(cell):
    by = defaultdict(list)
    for (s, _sp), v in cell.items():
        by[s].append(v)
    return {s: st.fmean(v) for s, v in sorted(by.items())}, \
           {s: len(v) for s, v in sorted(by.items())}


def summ(vals):
    n = len(vals)
    m = st.fmean(vals)
    sd = st.stdev(vals) if n > 1 else float("nan")
    sem = sd / math.sqrt(n) if n > 1 else float("nan")
    return m, sd, sem, n


def fmt(x, d=4):
    return "—" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{d}f}"


def main():
    d = load()
    arms = sorted({a for a, _, _ in d}, key=lambda a: list(ARM_LABEL).index(a)
                  if a in ARM_LABEL else 99)
    metrics = sorted({m for _, _, m in d})
    L = []
    w = L.append
    w("# Norman competitors — every metric, per seed and per split\n")
    w("_Generated by `scripts/norman/write_competitor_seed_report.py` from "
      "`data/release/metrics/norman_competitors_by_seed_split.csv`. Do not edit by hand; "
      "re-run the script._\n")
    w("## Protocol\n")
    w("| | |\n|---|---|")
    w("| benchmark | `norman_combo` — Norman 2019 K562 CRISPRa, rebuilt from GEO GSE133344 |")
    w("| task | train on 105 single-gene conditions; predict 111 held-out double pairs "
      "whose two genes were each seen singly |")
    w("| axis | 8,000 genes, sha256 `6efa91af1af5c8b8…` — identical for every arm and "
      "for Occam |")
    w("| scored panels | `additive` and `nonadditive`, 36 pairs each, "
      "**effect-size-controlled** (additivity residual terciled within effect-size "
      "terciles) |")
    w("| protocol | paired split-half: half A is the reference, half B the target, the "
      "model is fed half-B controls; 5 seeded splits |")
    w("| scorer | cell-eval 0.6.0, `nocal` (no calibration) |")
    w("| replication | seeds 42–46, **5 splits per seed**. Seed is the unit of "
      "replication: each seed's value is the mean of its 5 splits, and every SD / SEM "
      "below is ACROSS SEEDS |")
    w("")
    w("| arm | how it composes a pair | seeds |")
    w("|---|---|---|")
    for a in arms:
        seeds = sorted({s for (aa, p, m), c in d.items() if aa == a for (s, _) in c})
        w(f"| {ARM_LABEL.get(a, a)} | {MECH.get(a, '—')} | {', '.join(map(str, seeds))} "
          f"(n={len(seeds)}) |")
    w("")
    w("**Direction.** Higher is better except `mae`, `mse`, `mae_delta`, `mse_delta` "
      "(ERRORS, lower better). `discrimination_score_*` has chance at 0.5. "
      "`de_nsig_counts_*` and `n_perturbations` are counts, not quality, and must not be "
      "ranked on.\n")

    # --- 1. headline: seed-mean +- SD +- SEM, 4 metrics, both panels
    w("## 1. Headline — mean across seeds (± SD, ± SEM), the four reported metrics\n")
    for pn in PANELS:
        w(f"### `{pn}` panel\n")
        w("| arm | n seeds | " + " | ".join(
            f"`{m}` {'↓' if m in LOWER else '↑'}" for m in HEAD) + " |")
        w("|---|---|" + "---|" * len(HEAD))
        for a in arms:
            cells = []
            n = 0
            for m in HEAD:
                c = d.get((a, pn, m))
                if not c:
                    cells.append("—")
                    continue
                sm, _ = seed_means(c)
                mu, sd, sem, n = summ(list(sm.values()))
                cells.append(f"{fmt(mu)} ± {fmt(sd)} (± {fmt(sem)})")
            w(f"| **{ARM_LABEL.get(a, a)}** | {n} | " + " | ".join(cells) + " |")
        w("\n_Format: mean ± SD (± SEM), all across seeds._\n")

    # --- 2. per seed, 4 metrics
    w("## 2. Per seed — each value the mean of that seed's 5 splits\n")
    for pn in PANELS:
        for m in HEAD:
            w(f"### `{m}` {'↓ (ERROR)' if m in LOWER else '↑'} · `{pn}`\n")
            all_seeds = sorted({s for a in arms for (s, _) in d.get((a, pn, m), {})})
            w("| arm | " + " | ".join(f"s{s}" for s in all_seeds) +
              " | mean | SD | min | max |")
            w("|---|" + "---|" * (len(all_seeds) + 4))
            for a in arms:
                c = d.get((a, pn, m))
                if not c:
                    continue
                sm, _ = seed_means(c)
                vals = list(sm.values())
                mu, sd, _, _ = summ(vals)
                row = [fmt(sm.get(s)) if s in sm else "*pending*" for s in all_seeds]
                w(f"| {ARM_LABEL.get(a, a)} | " + " | ".join(row) +
                  f" | **{fmt(mu)}** | {fmt(sd)} | {fmt(min(vals))} | {fmt(max(vals))} |")
            w("")

    # --- 3. seed x split grid, pearson_delta
    w("## 3. Seed × split — `pearson_delta`, every individual measurement\n")
    w("The 5 splits are the SAME seeded halves for every seed and every arm "
      "(`blake2b(SPLIT_SALT|seed|split|group)`), so a column is comparable down a table.\n")
    for pn in PANELS:
        for a in arms:
            c = d.get((a, pn, "pearson_delta"))
            if not c:
                continue
            seeds = sorted({s for s, _ in c})
            w(f"### {ARM_LABEL.get(a, a)} · `{pn}`\n")
            w("| seed | split 0 | split 1 | split 2 | split 3 | split 4 | seed mean | "
              "split range |")
            w("|---|---|---|---|---|---|---|---|")
            for s in seeds:
                v = [c.get((s, i)) for i in range(5)]
                got = [x for x in v if x is not None]
                w(f"| {s} | " + " | ".join(fmt(x) for x in v) +
                  f" | **{fmt(st.fmean(got))}** | {fmt(max(got) - min(got))} |")
            w("")

    # --- 4. every metric
    w("## 4. Every cell-eval metric — mean ± SD across seeds\n")
    w("All 27 metrics cell-eval 0.6.0 produces. ⚠️ Counts (`de_nsig_counts_*`, "
      "`n_perturbations`) are context, not quality.\n")
    for pn in PANELS:
        w(f"### `{pn}` panel\n")
        w("| metric | dir | " + " | ".join(ARM_LABEL.get(a, a) for a in arms) + " |")
        w("|---|---|" + "---|" * len(arms))
        for m in metrics:
            dr = "count" if m in CONTEXT else ("↓" if m in LOWER else "↑")
            cells = []
            for a in arms:
                c = d.get((a, pn, m))
                if not c:
                    cells.append("—")
                    continue
                sm, _ = seed_means(c)
                mu, sd, _, _ = summ(list(sm.values()))
                cells.append(f"{fmt(mu)} ± {fmt(sd)}")
            w(f"| `{m}` | {dr} | " + " | ".join(cells) + " |")
        w("")
    w("## Raw data\n")
    w("Every value above, per seed × split × panel × metric, with the path of the "
      "`results.csv` it was read from: "
      "`data/release/metrics/norman_competitors_by_seed_split.csv`.")
    open(OUT, "w").write("\n".join(L) + "\n")
    print(f"wrote {os.path.relpath(OUT, REPO)} ({len(L)} lines)")


if __name__ == "__main__":
    main()
