#!/usr/bin/env python
"""Emit the (arm, composition mode) grid for the norman_combo model eval.

One row per (arm, mode); the launcher adds the 5 splits, so the array is 5x the row count.

WHY A GENERATED GRID
    12 modes x 6 arms is 72 rows, and every row has to name the arm's full run-suffix tag --
    which is derived from its loss weights and is 60+ characters. Hand-writing that invites
    exactly one kind of error: a tag that does not resolve, which shows up as
    "checkpoint missing" 72 times. This reads the tags off disk.

⚠️ It also REFUSES to emit a row whose checkpoint does not exist, rather than emitting it and
letting 5 array tasks fail. An arm still training is a reason to wait, not to queue.

    python scripts/norman/build_mode_grid.py [--modes sum,delta_sum,...]
"""
from __future__ import annotations

import argparse
import glob
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(REPO, "src"))

ARMS = ["NM03", "NM06", "NQ02", "NM03s", "NM06s", "NQ02s"]



def main(argv=None):
    from occam.vcell.model import VirtualCellModel

    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--arms", default=",".join(ARMS))
    ap.add_argument("--modes", default=",".join(VirtualCellModel.COMPOSE_MODES))
    ap.add_argument("--out", default="configs/norman_mode_eval.tsv")
    ap.add_argument("--allow-missing", action="store_true",
                    help="emit rows for arms whose checkpoint is absent (default: refuse)")
    a = ap.parse_args(argv)

    arms = [x.strip() for x in a.arms.split(",") if x.strip()]
    modes = [x.strip() for x in a.modes.split(",") if x.strip()]
    bad = sorted(set(modes) - set(VirtualCellModel.COMPOSE_MODES))
    if bad:
        raise SystemExit(f"unknown mode(s) {bad}; expected "
                         f"{list(VirtualCellModel.COMPOSE_MODES)}")

    tags, missing = {}, []
    for arm in arms:
        hits = sorted(glob.glob(f"runs/norman_combo_{arm}__*"))
        if not hits:
            missing.append(f"{arm}: no run directory")
            continue
        tag = os.path.basename(hits[0]).split("__", 1)[1]
        ck = f"runs/norman_combo_{arm}__{tag}/vcell/checkpoints/best_model.pth"
        if not os.path.isfile(ck):
            missing.append(f"{arm}: {ck} not written yet")
            continue
        # ⚠️ `best_model.pth` ALONE IS NOT A COMPLETION MARKER -- it is rewritten at every
        # eval epoch, so an arm at epoch 30 of 150 looks the same on disk as a finished one.
        # Scoring that reports a partial trajectory as a finished arm, which is what happened
        # on the W grid (four arms scored at epochs 70-82 of 90 before it was caught).
        # `final_model.pth` IS the marker: it is written once, at the end of training.
        final = f"runs/norman_combo_{arm}__{tag}/vcell/checkpoints/final_model.pth"
        if not os.path.isfile(final):
            missing.append(f"{arm}: final_model.pth absent -- still training")
            continue
        tags[arm] = tag
    if missing and not a.allow_missing:
        raise SystemExit("refusing to emit a grid with unresolvable arms:\n  "
                         + "\n  ".join(missing)
                         + "\n(they are probably still training; re-run when they finish, "
                           "or pass --allow-missing)")

    real = set(VirtualCellModel.REAL_BASE_MODES)
    lines = [
        "# norman_combo model eval: one row per (arm, composition mode); x5 splits in the",
        "# launcher. GENERATED by scripts/norman/build_mode_grid.py -- do not hand-edit.",
        "#",
        "# ⚠️ TWO EMISSION FAMILIES. These modes add their deltas to the REAL control cell",
        f"#    ({', '.join(sorted(real))}) and are comparable to EACH OTHER;",
        "#    the rest add them to the model's own reconstruction. The families differ on a",
        "#    single perturbation by the decoder's reconstruction error, which F-recon1",
        "#    measured as larger than the effect itself.",
        "#",
        f"#   sbatch --qos=vco --wckey=vco --array=0-{len(tags)*len(modes)*5 - 1}%6 \\",
        "#          scripts/slurm/norman_models.sbatch",
        "arm_id\ttag\tcompose",
    ]
    for arm in arms:
        if arm not in tags:
            continue
        for m in modes:
            lines.append(f"{arm}\t{tags[arm]}\t{m}")
    with open(a.out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    n_rows = len(tags) * len(modes)
    print(f"[grid] {a.out}: {len(tags)} arm(s) x {len(modes)} mode(s) = {n_rows} rows "
          f"-> --array=0-{n_rows * 5 - 1}%6  ({n_rows * 5} tasks)")
    for arm in arms:
        print(f"    {arm:6} {'OK  ' + tags[arm][:52] if arm in tags else 'MISSING'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
