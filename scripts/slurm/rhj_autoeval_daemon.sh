#!/usr/bin/env bash
#SBATCH --job-name=rhj_autoeval
#SBATCH --partition=cpu
#SBATCH --wckey=hooke-predict
#SBATCH --cpus-per-task=2
#SBATCH --mem=8G
#SBATCH --time=4-00:00:00
#SBATCH --output=runs/slurm/rhj_autoeval_%j.out
#SBATCH --error=runs/slurm/rhj_autoeval_%j.err
# =====================================================================
# AUTO-EVAL (RHJ): score every rhj_fewshot Occam arm the moment its training finishes.
#
# The RHJ twin of scripts/norman/autoeval_daemon.sh -- same logic, same reasons:
#   * rhj_loss_sweep.sbatch is training-only; the eval is a separate submission.
#   * the run-dir TAG is only known once the run dir exists, so no `afterok` dependency.
#   * `final_model.pth` is the COMPLETION marker; `best_model.pth` is what gets SCORED.
#
# Default owned arms: RB<bs> (the Y06 batch-size ladder, scripts/grids/rhj_batch.tsv) and
# S<seed>_Y06 (seed replicates, scripts/grids/rhj_seeds.tsv, if ever launched).
# Walltime 4 days because the bs-32 arm is allowed 72 h of training.
#
# Per arm it writes configs/autoeval_rhj_<arm>.tsv (`arm kind tag`) and submits
#   rhj_splithalf_models.sbatch --array=0-4%6   (5 splits, CALIBRATE=none -- nocal only)
#
# USAGE   sbatch scripts/slurm/rhj_autoeval_daemon.sh
#         ARMS_RE='^RB[0-9]+$' POLL_SECS=600 sbatch scripts/slurm/rhj_autoeval_daemon.sh
# =====================================================================
set -uo pipefail

HERE="$(cd "${SLURM_SUBMIT_DIR:-$(dirname "${BASH_SOURCE[0]}")/../..}" && pwd)"
cd "$HERE" || exit 1
mkdir -p runs/slurm runs/rhj_splithalf

POLL_SECS="${POLL_SECS:-600}"
ARMS_RE="${ARMS_RE:-^(RB[0-9]+|S[0-9]+_Y06)$}"
LEDGER="${LEDGER:-runs/rhj_splithalf/autoeval_submitted.txt}"
DEADLINE=$(( $(date +%s) + ${MAX_SECS:-342000} ))  # 95 h, inside the 96 h walltime
touch "$LEDGER"

echo "=== rhj auto-eval daemon ==="
echo "started : $(date -Is)   host $(hostname)   job ${SLURM_JOB_ID:-none}"
echo "git sha : $(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
echo "arms    : regex $ARMS_RE   poll ${POLL_SECS}s"
echo "ledger  : $LEDGER ($(wc -l < "$LEDGER") already submitted)"
echo

round=0
while [ "$(date +%s)" -lt "$DEADLINE" ]; do
    round=$(( round + 1 ))
    found=0; new=0
    for marker in runs/rhj_fewshot_*/vcell/checkpoints/final_model.pth; do
        [ -f "$marker" ] || continue
        rundir="${marker%/vcell/checkpoints/final_model.pth}"
        rest="$(basename "$rundir")"; rest="${rest#rhj_fewshot_}"
        arm="${rest%%__*}"; tag="${rest#*__}"
        echo "$arm" | grep -qE "$ARMS_RE" || continue
        found=$(( found + 1 ))
        grep -qxF "$arm" "$LEDGER" && continue
        if [ ! -f "$rundir/vcell/checkpoints/best_model.pth" ]; then
            echo "[$(date +%H:%M:%S)] $arm: final_model present but NO best_model -- not scoring." >&2
            echo "$arm" >> "$LEDGER"
            continue
        fi
        grid="configs/autoeval_rhj_${arm}.tsv"
        {
            echo "# auto-generated by scripts/slurm/rhj_autoeval_daemon.sh $(date -Is)"
            printf 'arm_id\tkind\ttag\n'
            printf '%s\tloss\t%s\n' "$arm" "$tag"
        } > "$grid"
        jid=$(sbatch --parsable --qos=hooke-predict --wckey=hooke-predict \
                     --array=0-4%6 \
                     --export=ALL,GRID="$grid",N_SPLITS=5,CALIBRATE=none \
                     scripts/slurm/rhj_splithalf_models.sbatch 2>&1 | tail -1)
        if echo "$jid" | grep -qE '^[0-9]+$'; then
            echo "$arm" >> "$LEDGER"; new=$(( new + 1 ))
            echo "[$(date +%H:%M:%S)] SUBMITTED $arm ($tag) -> job $jid, 5 task(s)"
        else
            echo "[$(date +%H:%M:%S)] $arm: sbatch FAILED, will retry next poll: $jid" >&2
        fi
    done
    echo "[$(date +%H:%M:%S)] round $round: $found finished arm(s) matching, $new new," \
         "$(wc -l < "$LEDGER") in ledger"
    sleep "$POLL_SECS"
done
echo "=== daemon walltime reached: $(date -Is) -- later arms are NOT scored ==="
